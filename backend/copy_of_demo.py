class exp3_interactive:
    def __init__(self, sim, env, T, K=1):
        self.sim = sim
        self.env = env
        self.K = K
        self.n_arms = sim.n_sites
        self.p = np.ones(self.n_arms) / self.n_arms

        self.cum_reward = np.zeros(self.n_arms)
        self.his_reward = np.zeros((self.n_arms, T))

        self.L = 100
        self.eta = np.sqrt(np.log(self.n_arms) / (T * self.n_arms * self.L**2))

        # self.curr_total_screened = 0
        # self.curr_total_diagnosed = 0

    def apply_user_selection(self, selected_indices):
        self.env.update(self.sim)

        actions = np.zeros(self.n_arms, dtype=int)
        actions[selected_indices] = 1

        self.sim.step(actions=actions)
        observation = self.sim.get_observable()

        # self.curr_total_screened = observation.sum()
        # self.curr_total_diagnosed = observation[:, 0].sum()

        indx = observation[:, 0] == 0
        self.reward = np.zeros(len(observation.sum(axis=1)))
        self.reward[indx] = - observation.sum(axis=1)[indx] / (0.1 + observation[:, 0][indx])
        self.reward[~indx] = - observation.sum(axis=1)[~indx] / observation[:, 0][~indx]

        R_hat = np.zeros(self.n_arms)
        R_hat[selected_indices] = self.reward[selected_indices]  / self.p[selected_indices]

        self.cum_reward += R_hat
        self.p = logsumexp_trick(self.eta * self.cum_reward)
        self.p = (1 - self.eta) * self.p + self.eta / self.n_arms


    def get_site_recommendation(self, top_k=None):
        """
        Returns a DataFrame with current model recommendations (not cumulative).
        Fields:
        - zip_code
        - priority (model score)
        - rank
        If top_k is provided, limits to top_k arms.
        """
        sorted_indices = np.argsort(-self.p)
        probs_sorted = self.p[sorted_indices]

        if top_k:
            sorted_indices = sorted_indices[:top_k]
            probs_sorted = probs_sorted[:top_k]
        else:
            sorted_indices = sorted_indices
            probs_sorted = probs_sorted

        recommendations = {
            "zip_code": [f"{i}" for i in sorted_indices],
            "priority": probs_sorted,
            "rank": np.arange(1, len(sorted_indices) + 1)
        }
        return recommendations

    def get_site_report(self, t, selected_indices):
        """
        Returns report only for selected arms (non-zero screened).
        Each entry includes:
        - zip_code: site_{i}
        - screened_count: diagnosed + others
        - positive_count: diagnosed
        - priority: from self.p
        - notes: empty
        """
        obs = self.sim.get_observable()
        report = []
        for i in selected_indices:
            screened_count = int(obs[i].sum())
            positive_count = int(obs[i, 0])
            report.append({
                "screening_week": t,
                "zip_code": f"{i}",
                "screened_count": screened_count,
                "positive_count": positive_count,
                "notes": ""
            })
        return report



    def reset(self, reset_sim=True):
        if reset_sim:
            self.sim.reset()
        self.p = np.ones(self.n_arms) / self.n_arms
        self.cum_reward = np.zeros(self.n_arms)
        self.his_reward = np.zeros_like(self.his_reward)
        self.curr_total_screened = 0
        self.curr_total_diagnosed = 0

