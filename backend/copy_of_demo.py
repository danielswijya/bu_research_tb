class LinUCB_interactive:
    def __init__(self, sim, env, T, alpha=1.0, lam=1.0, K=1, reg=None):
        self.sim = sim
        self.env = env
        self.T = T
        self.K = K
        self.alpha = alpha
        self.lam = lam

        self.n_arms = sim.n_sites
        self.n_dims = env.n_dims

        self.A = np.tile(np.eye(self.n_dims) * self.lam, (self.n_arms, 1, 1))
        self.b = np.zeros((self.n_arms, self.n_dims, 1))
        self.theta = np.zeros((self.n_arms, self.n_dims, 1))

        self.theta_star = np.zeros((self.n_arms, self.n_dims, 1)) if reg is None else reg
        self.t = 1
        self.reward = np.zeros(self.n_arms)

        self.last_context = None

    def apply_user_selection(self, selected_indices):
        self.env.update(self.sim)

        actions = np.zeros(self.n_arms, dtype=int)
        actions[selected_indices] = 1

        self.sim.step(actions=actions)
        observation = self.sim.get_observable()

        indx = observation[:, 0] == 0
        self.reward = np.zeros(len(observation.sum(axis=1)))
        self.reward[indx] = - observation.sum(axis=1)[indx] / (0.1 + observation[:, 0][indx])
        self.reward[~indx] = - observation.sum(axis=1)[~indx] / observation[:, 0][~indx]

        # get pulled arm
        indx = np.where(self.sim.status)[0]
        # update: over each selected arm:
        for n, i in enumerate(indx):
            observe_feature = self.last_context[i].reshape(-1, 1)

            # no decay update
            self.A[i] += observe_feature @ observe_feature.T
            self.b[i] += self.reward[n] * observe_feature

        self.t += 1

    def get_site_recommendation(self, top_k=None):
        """
        Returns a dictionary with current model recommendations (not cumulative).
        Fields:
        - zip_code
        - priority (model score)
        - rank
        If top_k is provided, limits to top_k arms.
        """
        self.env.update(self.sim)
        X = self.env.get_context()
        self.last_context = X

        scores = np.zeros(self.n_arms)
        for i in range(self.n_arms):
            A_inv = np.linalg.pinv(self.A[i])
            decay = (self.T - self.t) / self.T
            self.theta[i] = A_inv @ (self.b[i] + self.lam * decay * self.theta_star[i])
            scores[i] = (self.theta[i].T @ X[i] + self.alpha * np.sqrt(X[i].T @ A_inv @ X[i])).item()

        sorted_indices = np.argsort(-scores)
        probs_sorted = scores[sorted_indices]

        if top_k:
            sorted_indices = sorted_indices[:top_k]
            probs_sorted = probs_sorted[:top_k]

        recommendations = {
            "zip_code": [f"{i}" for i in sorted_indices],
            "priority": probs_sorted,
            "rank": np.arange(1, len(sorted_indices) + 1)
        }
        return recommendations

    def get_site_report(self, t):
        """
        Returns report only for selected arms (non-zero screened).
        Each entry includes:
        - screening_week
        - zip_code
        - screened_count: diagnosed + others
        - positive_count: diagnosed
        - notes: ""
        """
        obs = self.sim.get_observable()
        report = []
        indx = np.where(self.sim.status)[0]
        # update: over each selected arm:
        for n, i in enumerate(indx):
            screened_count = int(obs[n].sum())
            positive_count = int(obs[n, 0])
            report.append({
                "screening_week": t,
                "zip_code": f"{i}",
                "screened_count": screened_count,
                "positive_count": positive_count,
                "notes": ""
            })
        return report

    def reset(self, reset_sim=True):
        if reset_sim:
            self.sim.reset()
            self.env.reset()

        self.A = np.tile(np.eye(self.n_dims) * self.lam, (self.n_arms, 1, 1))
        self.b = np.zeros((self.n_arms, self.n_dims, 1))
        self.theta = np.zeros((self.n_arms, self.n_dims, 1))
        self.reward = np.zeros(self.n_arms)
        self.t = 1
        self.last_context = None

